const assert=require('node:assert/strict');
const {runCampusTool:run}=require('../campus-tools.cjs');
let result=run('图书馆借书能借多久？');
assert.equal(result.context.task,'library_borrowing');
assert.equal(result.options.length,4);
result=run('本科生',result.context);
assert.match(result.answer,/30册.*1个月/);
result=run('其实我是硕士研究生',result.context);
assert.match(result.answer,/50册.*2个月/);
result=run('怎么续借',result.context);
assert.match(result.answer,/逾期或被他人预约的图书不能办理续借|有预约记录和过期的图书不可续借/);
result=run('图书可以借多久？',result.context);
assert.match(result.answer,/50册.*2个月/);
assert.equal(run('校园网连不上怎么办？',result.context).context.task,'campus_network');
assert.equal(run('研究生',{}),null);
result=run('借书能借多久？我是研究生');
assert.deepEqual(result.options,['硕士研究生','博士研究生']);
let network=run('校园网连不上怎么办？');
network=run('SUIBE',network.context);
assert.match(network.answer,/每7天/);
assert.doesNotMatch(network.answer,/eduroam/);
console.log('Library and network workflow assertions passed');
